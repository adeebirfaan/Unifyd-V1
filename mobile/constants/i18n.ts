export function translate(language: LanguagePreference, key: TranslationKey, values?: Record<string, string | number>): string {
  const template = language === 'ms' ? ms[key] : en[key];
  return values ? template.replace(/\{(\w+)\}/g, (match, name: string) => String(values[name] ?? match)) : template;
}
