// Copies only the brand marks Unifyd uses from the locally installed `simple-icons` package (CC0-1.0)
// into constants/brandMarks.generated.ts. The full package is ~5 MB of JavaScript and Metro does not drop
// unused exports, so the app bundles just these few paths instead. Run after upgrading simple-icons:
//   node scripts/generate-brand-marks.mjs
// No network access: everything is read from node_modules.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const icons = require('simple-icons');
const { version } = JSON.parse(readFileSync(new URL('../node_modules/simple-icons/package.json', import.meta.url), 'utf8'));

// Brand key → simple-icons export. The matching rules that use these keys live in lib/subscriptionBrands.ts.
export const MARKS = {
  spotify: 'siSpotify',
  youtube: 'siYoutube',
  claude: 'siClaude',
  anthropic: 'siAnthropic',
  netflix: 'siNetflix',
  appleMusic: 'siApplemusic',
  icloud: 'siIcloud',
  googleDrive: 'siGoogledrive',
  notion: 'siNotion',
  grammarly: 'siGrammarly',
  duolingo: 'siDuolingo',
  figma: 'siFigma',
  dropbox: 'siDropbox',
  zoom: 'siZoom',
};

const entries = Object.entries(MARKS).map(([key, exportName]) => {
  const icon = icons[exportName];
  if (!icon) throw new Error(`${exportName} is not in simple-icons ${version}`);
  return `  ${key}: { title: ${JSON.stringify(icon.title)}, slug: ${JSON.stringify(icon.slug)}, path: ${JSON.stringify(icon.path)} },`;
});

const out = `// GENERATED by scripts/generate-brand-marks.mjs from simple-icons ${version} (CC0-1.0). Do not edit by hand.
// Brand marks are trademarks of their owners. They are shown only to identify a student's own subscription
// and imply no affiliation with or endorsement of Unifyd. Paths use a 24 × 24 view box.
export const SIMPLE_ICONS_VERSION = ${JSON.stringify(version)};

export const BRAND_MARKS = {
${entries.join('\n')}
} as const;

export type BrandMarkKey = keyof typeof BRAND_MARKS;
`;
writeFileSync(fileURLToPath(new URL('../constants/brandMarks.generated.ts', import.meta.url)), out);
console.log(`Wrote ${entries.length} marks from simple-icons ${version}.`);
